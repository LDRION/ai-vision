def describe_marks(elements: List[dict], limit: int = 220) -> str:
    rows = [
        f"[{e['id']}] {e.get('role', 'текст')} «{redact(e['text'])[:60]}» "
        + (f"= «{redact(str(e['value']))[:40]}» " if e.get('value') else '')
        + f"x {e['box'][0]}–{e['box'][2]}, y {e['box'][1]}–{e['box'][3]}" + (' [новое]' if e.get('new') else '')
        for e in elements[:limit]
    ]
    if len(elements) > limit:
        rows.append(f'… ещё {len(elements) - limit} — номера видны на скриншоте')
    return '\n'.join(rows) if rows else '(элементов не найдено — только сетка)'


def step_prompt(goal: str, step: int, max_steps: int, history: List[str], title: str,
                size, grid: int, elements: List[dict], lessons: List[str] = (),
                hints: List[str] = (), cursor=None, windows: str = '', notes: List[str] = ()) -> str:
    hist = '\n'.join(history) if history else '(это первый шаг)'
    exp = ''.join(f'- {x}\n' for x in lessons)
    tips = ''.join(f'- {x}\n' for x in hints)
    return (
        f"ЦЕЛЬ: {goal}\n\n"
        + (f"ПОДСКАЗКИ ПОЛЬЗОВАТЕЛЯ (следуй им):\n{tips}\n" if tips else '') +
        f"Шаг {step} из {max_steps}.\n"
        f"ИСТОРИЯ:\n{hist}\n\n"
        + (f"ОПЫТ (уроки прошлых задач):\n{exp}\n" if exp else '') +
        f"Активное окно: «{title or 'неизвестно'}»\n"
        + (f"ОТКРЫТЫЕ ОКНА:\n{windows}\n" if windows else '')
        + ''.join(f"{x}\n" for x in notes)
        + (f"Курсор сейчас в ({cursor[0]}, {cursor[1]}).\n" if cursor else '') +
        f"Экран {size[0]}×{size[1]} px, шаг сетки {grid} px.\n"
        f"Элементы:\n{describe_marks(elements)}\n\n"
        f"Ответь одним JSON."
    )


