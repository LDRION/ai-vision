ZONES = (('ВЛ', 'ВЦ', 'ВП'), ('СЛ', 'СЦ', 'СП'), ('НЛ', 'НЦ', 'НП'))
STATES = {'on': 'вкл', 'off': 'выкл', 'selected': 'выбрано'}


def zone(box, size) -> str:
    cx, cy = (box[0] + box[2]) / 2, (box[1] + box[3]) / 2
    col = min(2, max(0, int(3 * cx / max(size[0], 1))))
    row = min(2, max(0, int(3 * cy / max(size[1], 1))))
    return ZONES[row][col]


def describe_marks_text(elements: List[dict], size, limit: int = 260) -> str:
    """Список элементов для шага без скриншота: подпись, значение, состояние, зона — без координат."""
    rows = []
    for e in elements[:limit]:
        r = f"[{e['id']}] {e.get('role', 'текст')} «{redact(e['text'])[:60]}»"
        if e.get('value'):
            r += f" = «{redact(str(e['value']))[:40]}»"
        if e.get('state'):
            r += f" [{STATES.get(e['state'], e['state'])}]"
        rows.append(f"{r} · {zone(e['box'], size)}" + (' [новое]' if e.get('new') else ''))
    if len(elements) > limit:
        rows.append(f'… ещё {len(elements) - limit} элементов не показано')
    return '\n'.join(rows) if rows else '(элементов не найдено)'


